"""CLI to encrypt existing plaintext / legacy Fernet API keys in the database.

This tool handles three history formats:
1. **Plaintext** — raw API key stored directly in the DB.
2. **Legacy Fernet token** — ``cryptography.fernet`` token without ``enc:v1:`` prefix
   (generated by old code when ``AI_CONFIG_ENCRYPT_KEY`` was configured).
3. **``enc:v1:<token>``** — current envelope format; skipped if decryptable.

Usage:
    python -m app.cli.encrypt_ai_secrets              # preview count
    python -m app.cli.encrypt_ai_secrets --dry-run     # show details
    python -m app.cli.encrypt_ai_secrets --execute     # perform migration

Safe to run multiple times — skips already-encrypted values.
"""

from __future__ import annotations

import argparse
import logging
import sys

logger = logging.getLogger("encrypt_ai_secrets")


def _parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Encrypt plaintext / legacy-format API keys in the database.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show what would be migrated without modifying the database.",
    )
    parser.add_argument(
        "--execute",
        action="store_true",
        help="Actually perform the migration (default is preview-only).",
    )
    return parser.parse_args(argv)


def _count_pending(
    rows: list[tuple],
    field_idx: int,
) -> int:
    """Count values that are not NULL and not enc:v1: prefixed."""
    from app.core.secret_crypto import ENCRYPTED_PREFIX

    return sum(
        1 for r in rows
        if r[field_idx] is not None and not r[field_idx].startswith(ENCRYPTED_PREFIX)
    )


def _categorise(value: str) -> str:
    """Categorise a value: plaintext, legacy_fernet, enc_v1, enc_unknown, or empty."""
    if not value:
        return "empty"
    if value.startswith("enc:v1:"):
        return "enc_v1"
    if value.startswith("enc:"):
        return "enc_unknown"
    # Could be plaintext or legacy Fernet token (no prefix)
    # Legacy Fernet tokens are base64, start with "gAAAA"
    if value.startswith("gAAAA"):
        return "legacy_fernet"
    return "plaintext"


def _migrate_value(
    value: str,
    fernet_key: str,
) -> str:
    """Encrypt a single value, handling all history formats.

    Args:
        value: The stored DB value (plaintext, legacy Fernet, or enc:v1:).
        fernet_key: The Fernet key string.

    Returns:
        The ``enc:v1:`` envelope string.

    Raises:
        ValueError: Format is unsupported or migration not possible.
        cryptography.fernet.InvalidToken: Legacy token cannot be decrypted.
    """
    from cryptography.fernet import Fernet

    from app.core.secret_crypto import ENCRYPTED_PREFIX, encrypt_secret

    f = Fernet(fernet_key.encode())

    if value.startswith(ENCRYPTED_PREFIX):
        # Already in target format — verify it's decryptable
        token = value[len(ENCRYPTED_PREFIX):]
        if not token:
            raise ValueError("enc:v1: envelope is empty")
        f.decrypt(token.encode())  # verify; raises InvalidToken on failure
        return value  # already valid, no change needed

    if value.startswith("gAAAA"):
        # Legacy Fernet token — decrypt then re-encrypt
        plain = f.decrypt(value.encode()).decode()
    else:
        # Treat as plaintext
        plain = value

    return encrypt_secret(plain)


def main(argv: list[str] | None = None) -> None:
    """CLI entry point."""
    args = _parse_args(argv)

    # 1. Check encryption key
    from app.core.config import settings

    if not settings.AI_CONFIG_ENCRYPT_KEY:
        logger.error("AI_CONFIG_ENCRYPT_KEY is not configured — cannot encrypt secrets.")
        sys.exit(1)

    try:
        from cryptography.fernet import Fernet
        Fernet(settings.AI_CONFIG_ENCRYPT_KEY.encode())
    except Exception as exc:
        logger.error("AI_CONFIG_ENCRYPT_KEY is invalid: %s", exc)
        sys.exit(1)

    # 2. Connect to DB
    from app.core.database import engine

    # Tables to migrate: (table, pk_column, secret_column, display_name)
    tables = [
        ("admin_ai_model_configs", "id", "api_key_encrypted", "AI model config"),
        ("admin_vector_configs", "id", "embedding_api_key_encrypted", "Vector config"),
    ]

    total_processed = 0
    total_skipped = 0
    total_encrypted = 0
    total_errors: list[str] = []

    is_pg = "postgresql" in settings.DATABASE_URL

    async def _run():
        nonlocal total_processed, total_skipped, total_encrypted, total_errors

        from sqlalchemy import text

        async with engine.connect() as conn:
            # Phase 1: Collect pending records (outside transaction to preview)
            all_pending: list[tuple[str, int, str, str]] = []  # (table, pk, value, label)

            for table_name, pk_col, secret_col, label in tables:
                result = await conn.execute(
                    text(f"SELECT {pk_col}, {secret_col} FROM {table_name}")
                )
                rows = result.all()
                for row in rows:
                    pk = row[0]
                    val = row[1]
                    if val is None:
                        total_skipped += 1
                        continue
                    category = _categorise(val)
                    if category == "enc_v1":
                        total_skipped += 1
                        continue
                    if category == "enc_unknown":
                        total_errors.append(
                            f"Unknown envelope version in {label} (pk={pk}) — "
                            "cannot migrate automatically"
                        )
                        continue
                    all_pending.append((table_name, pk, val, label))
                    total_processed += 1

            # Report
            logger.info(
                "Migration preview: %d pending, %d skipped, %d errors",
                total_processed, total_skipped, len(total_errors),
            )
            for err in total_errors:
                logger.error("  %s", err)

            if not all_pending:
                logger.info("Nothing to migrate.")
                return

            if not args.execute:
                if args.dry_run:
                    logger.info("--dry-run: records that would be migrated:")
                    for tname, pk, val, label in all_pending:
                        cat = _categorise(val)
                        logger.info("  %s (pk=%s): %s", label, pk, cat)
                else:
                    logger.info(
                        "Run with --dry-run for details or --execute to migrate."
                    )
                return

            # Phase 2: Execute migration in transaction
            async with conn.begin():
                if is_pg:
                    # Lock rows for concurrent safety
                    for table_name, pk_col, secret_col, label in tables:
                        await conn.execute(
                            text(
                                f"SELECT {pk_col}, {secret_col} "
                                f"FROM {table_name} "
                                f"WHERE {pk_col} IN :pks "
                                f"FOR UPDATE"
                            ),
                            {"pks": tuple(pk for tname, pk, _, _ in all_pending
                                          if tname == table_name)},
                        )

                for tname, pk, val, label in all_pending:
                    try:
                        encrypted = _migrate_value(val, settings.AI_CONFIG_ENCRYPT_KEY)
                        if encrypted == val:
                            # enc:v1: already valid — shouldn't happen but handle safely
                            total_skipped += 1
                            continue

                        # Update with optimistic locking (check value unchanged)
                        await conn.execute(
                            text(
                                f"UPDATE {tname} "
                                f"SET {secret_col} = :encrypted "
                                f"WHERE {secret_col} = :original AND id = :pk"
                            ),
                            {"encrypted": encrypted, "original": val, "pk": pk},
                        )
                        total_encrypted += 1
                    except Exception as exc:
                        total_errors.append(
                            f"Failed to migrate {label} (pk={pk}): {exc}"
                        )
                        raise  # roll back entire transaction

            # Phase 3: Verify
            logger.info(
                "Migration complete: %d encrypted, %d skipped, %d errors",
                total_encrypted, total_skipped, len(total_errors),
            )
            if total_errors:
                for err in total_errors:
                    logger.error("  ERROR: %s", err)

    import asyncio

    try:
        asyncio.run(_run())
    except Exception:
        logger.exception("Migration failed — all changes rolled back")
        sys.exit(1)

    if total_errors:
        sys.exit(1)


if __name__ == "__main__":
    main()
